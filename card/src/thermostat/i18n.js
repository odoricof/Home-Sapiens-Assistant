// Lingue supportate: it, en, de, es, fr, ru (come l'integrazione). Le altre usano l'inglese.
export const langOf = (hass) => {
  const code = String(hass?.language || "it").toLowerCase().split(/[-_]/)[0];
  return TXT[code] ? code : "en";
};

export const t = (hass, key) => TXT[langOf(hass)][key] ?? key;

// Velocità della ventola in italiano: "Basso", "Medio", "Alto" (senza "/a").
const FAN_LABELS_IT = { low: "Basso", medium: "Medio", high: "Alto" };
export const fanLabel = (hass, value) =>
  langOf(hass) === "it" ? FAN_LABELS_IT[value] : undefined;
